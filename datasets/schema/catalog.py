def validate_catalog() -> list[str]:
    """一次返回全部结构错误，方便开发者集中修复 catalog。

    校验在生成 JSON 和 SQL 之前运行。这里检查名称、主键、引用、基数和枚举声明；数据库
    运行期的数据一致性由外键、CHECK 约束和数据生成质量门禁负责。
    """

    errors: list[str] = []
    names = {table.name for table in TABLES}
    if len(names) != len(TABLES):
        errors.append("table names must be unique")
    for table in TABLES:
        column_names = {item.name for item in table.columns}
        if len(column_names) != len(table.columns):
            errors.append(f"{table.name}: column names must be unique")
        primary_keys = [item.name for item in table.columns if item.is_primary_key]
        if primary_keys != ["id"]:
            errors.append(f"{table.name}: expected id as the single primary key")
        for item in table.columns:
            if item.reference and item.reference.split(".", 1)[0] not in names:
                errors.append(f"{table.name}.{item.name}: unknown reference {item.reference}")
            if bool(item.reference) != bool(item.relationship_cardinality):
                errors.append(f"{table.name}.{item.name}: reference and cardinality must coexist")
        for enum_column in table.status_enums:
            if enum_column not in column_names:
                errors.append(f"{table.name}: enum column {enum_column} does not exist")
    return errors
